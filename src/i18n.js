function deepFreeze(value) {
  if (!value || typeof value !== 'object' || Object.isFrozen(value)) return value;
  for (const child of Object.values(value)) deepFreeze(child);
  return Object.freeze(value);
}

export const CATALOGS = deepFreeze({ en: EN, 'zh-Hans': ZH_HANS });

export function normalizeLocale(locale) {
  return locale === 'zh-Hans' || /^zh(?:-|$)/i.test(String(locale ?? '')) ? 'zh-Hans' : DEFAULT_LOCALE;
}

function interpolate(message, values = {}) {
  return message.replace(/\{([A-Za-z][A-Za-z0-9]*)\}/g, (match, name) => (
    Object.hasOwn(values, name) ? String(values[name]) : match
  ));
}

export function createI18n(initialLocale = DEFAULT_LOCALE) {
  let locale = normalizeLocale(initialLocale);
  const message = (key) => {
    const value = CATALOGS[locale][key] ?? CATALOGS[DEFAULT_LOCALE][key];
    if (value === undefined) throw new RangeError(`Missing translation: ${key}`);
    return value;
  };
  const t = (key, values) => {
    const value = message(key);
    if (typeof value !== 'string') throw new TypeError(`Translation requires plural selection: ${key}`);
    return interpolate(value, values);
  };
  const plural = (key, count, values = {}) => {
    const value = message(key);
    if (!value || typeof value !== 'object') return t(key, { ...values, count });
    const category = new Intl.PluralRules(locale).select(count);
    return interpolate(value[category] ?? value.other, { ...values, count: formatNumber(count) });
  };
  const formatNumber = (value) => new Intl.NumberFormat(locale).format(value);
  const isoDate = (value, options = { year: 'numeric', month: 'short', day: 'numeric' }) => {
    const match = /^(\d{4})-(\d{2})-(\d{2})$/.exec(String(value));
    if (!match) throw new RangeError('date must use YYYY-MM-DD');
    const [year, month, day] = match.slice(1).map(Number);
    const date = new Date(Date.UTC(year, month - 1, day, 12));
    if (date.getUTCFullYear() !== year || date.getUTCMonth() !== month - 1 || date.getUTCDate() !== day) {
      throw new RangeError('date must be a valid calendar date');
    }
    return new Intl.DateTimeFormat(locale, { ...options, timeZone: 'UTC' }).format(date);
  };
  return Object.freeze({
    get locale() { return locale; },
    setLocale(nextLocale) { locale = normalizeLocale(nextLocale); return locale; },
    t,
    plural,
    formatNumber,
    formatIsoDate: isoDate,
    formatDateTime(value) {
      return new Intl.DateTimeFormat(locale, { dateStyle: 'medium', timeStyle: 'medium' }).format(new Date(value));
    },
    formatMonth(value) { return isoDate(value, { month: 'short' }); },
    formatWeekday(value) { return isoDate(value, { weekday: 'long' }); },
  });
}

export function localizeDocument(root, i18n) {
  const documentNode = root?.nodeType === 9 ? root : root?.ownerDocument;
  if (!documentNode) return;
  documentNode.documentElement.lang = i18n.locale;
  documentNode.title = i18n.t('meta.title');
  const description = documentNode.querySelector('meta[name="description"]');
  if (description) description.setAttribute('content', i18n.t('meta.description'));
  for (const element of root.querySelectorAll('[data-i18n]')) {
    element.textContent = i18n.t(element.dataset.i18n);
  }
  for (const [dataName, attributeName] of [
    ['i18nAriaLabel', 'aria-label'],
    ['i18nPlaceholder', 'placeholder'],
    ['i18nTitle', 'title'],
    ['i18nDataStamp', 'data-stamp'],
  ]) {
    for (const element of root.querySelectorAll(`[data-${dataName.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`)}]`)) {
      element.setAttribute(attributeName, i18n.t(element.dataset[dataName]));
    }
  }
}

export function assertCatalogParity(catalogs = CATALOGS) {
  const expected = Object.keys(catalogs[DEFAULT_LOCALE]).sort();
  const placeholderNames = (value) => [...new Set(
    [...String(value).matchAll(/\{([A-Za-z0-9_.-]+)\}/g)].map((match) => match[1]),
  )].sort();
  for (const locale of SUPPORTED_LOCALES) {
    const actual = Object.keys(catalogs[locale]).sort();
    if (actual.length !== expected.length || actual.some((key, index) => key !== expected[index])) {
      throw new Error(`Translation catalog keys differ for ${locale}`);
    }
    for (const key of expected) {
      const baselineValue = catalogs[DEFAULT_LOCALE][key];
      const localeValue = catalogs[locale][key];
      const baselinePlural = typeof baselineValue === 'object' && baselineValue !== null && !Array.isArray(baselineValue);
      const localePlural = typeof localeValue === 'object' && localeValue !== null && !Array.isArray(localeValue);
      if (baselinePlural !== localePlural || (!baselinePlural && typeof baselineValue !== typeof localeValue)) {
        throw new TypeError(`Translation value type differs for ${locale}.${key}`);
      }
      if (baselinePlural && (typeof baselineValue.other !== 'string' || typeof localeValue.other !== 'string')) {
        throw new TypeError(`Plural translation requires an other form: ${locale}.${key}`);
      }
      const baselineText = baselinePlural ? Object.values(baselineValue).join('') : baselineValue;
      const localeText = localePlural ? Object.values(localeValue).join('') : localeValue;
      if (placeholderNames(baselineText).join('\0') !== placeholderNames(localeText).join('\0')) {
        throw new Error(`Translation placeholders differ for ${locale}.${key}`);
      }
    }
  }
  return true;
}
